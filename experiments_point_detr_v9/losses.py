"""
Unsupervised Stippling Losses for Point-RT V9.

This module implements the "Physics-Only" loss functions that don't require 
Ground Truth supervision. The model learns the optimal point distribution
directly from image density using optimal transport and repulsion physics.

Key insight: Traditional supervised learning is limited by GT quality.
If GT is generated by Lloyd's algorithm, the model learns Lloyd's artifacts.
This unsupervised approach finds the true equilibrium state.

Losses:
1. SinkhornDensityLoss - Capacity constraint (macroscopic)
   "The number of points in each region must match the sum of pixel darkness"
   
2. AdaptiveRepulsionLoss - Spacing constraint (microscopic)  
   "Points must spread out as much as local density allows (blue noise)"
"""

import torch
import torch.nn as nn
import torch.nn.functional as F
from typing import Tuple, Optional

# Try to import geomloss for Sinkhorn
try:
    from geomloss import SamplesLoss
    HAS_GEOMLOSS = True
except ImportError:
    HAS_GEOMLOSS = False
    print("[Warning] geomloss not installed. Install with: pip install geomloss")


class SinkhornDensityLoss(nn.Module):
    """
    Sinkhorn (Optimal Transport) Loss for matching point distribution to image density.
    
    This is the differentiable version of Capacity Constrained Voronoi Tessellation (CCVT).
    
    Theory:
    - Source: Predicted points (uniform weights)
    - Target: Image density (dark pixels = high probability mass)
    - Loss: Earth Mover's Distance between distributions
    
    The loss forces points to spread proportionally to image density.
    Clumping = high transport cost = penalized.
    """
    
    def __init__(self, blur: float = 0.05, grid_size: int = 32, scaling: float = 0.5, p: int = 2):
        """
        Initialize Sinkhorn loss.
        
        Args:
            blur: Smoothness of matching (0.05 = fast, good for training)
            grid_size: Resolution for target density grid (32 = fast)
            scaling: Sinkhorn algorithm convergence parameter (0.5 = fast)
            p: Power for Wasserstein distance (2 = squared Euclidean)
        """
        super().__init__()
        self.blur = blur
        self.grid_size = grid_size
        self.scaling = scaling
        self.p = p
        
        if HAS_GEOMLOSS:
            self.loss_fn = SamplesLoss(
                loss="sinkhorn", 
                p=p, 
                blur=blur,
                scaling=scaling,
                debias=True,
                backend="tensorized",
            )
        else:
            self.loss_fn = None
        
        # Create fixed coordinate grid for target density [-1, 1]
        y = torch.linspace(-1, 1, grid_size)
        x = torch.linspace(-1, 1, grid_size)
        grid_y, grid_x = torch.meshgrid(y, x, indexing='ij')
        self.register_buffer('target_coords', torch.stack([grid_x, grid_y], dim=-1).reshape(1, -1, 2))
    
    def forward(self, pred_points: torch.Tensor, input_images: torch.Tensor) -> torch.Tensor:
        """
        Compute Sinkhorn loss between points and image density.
        
        Args:
            pred_points: (B, N, 2) Source points in [-1, 1]
            input_images: (B, 1, H, W) Target density map (0=light, 1=dark)
        
        Returns:
            Sinkhorn divergence (scalar)
        """
        if not HAS_GEOMLOSS:
            return torch.tensor(0.0, device=pred_points.device, requires_grad=True)
        
        B, N, _ = pred_points.shape
        device = pred_points.device
        
        # 1. Source Distribution (Points) - uniform weights
        source_weights = torch.ones(B, N, device=device) / N
        source_coords = pred_points.contiguous()
        
        # 2. Target Distribution (Image)
        target_density = F.interpolate(
            input_images, 
            size=(self.grid_size, self.grid_size), 
            mode='bilinear',
            align_corners=False
        )
        
        # CRITICAL: Dark pixels need MORE points (invert)
        target_density = 1.0 - target_density
        
        target_density = target_density.view(B, -1)
        target_density = target_density.clamp(min=1e-6)
        target_weights = target_density / (target_density.sum(dim=1, keepdim=True) + 1e-8)
        
        target_coords = self.target_coords.expand(B, -1, -1).to(device).contiguous()
        
        # 3. Compute Wasserstein Distance
        loss = self.loss_fn(source_weights, source_coords, target_weights, target_coords)
        
        return loss.mean()


class AdaptiveRepulsionLoss(nn.Module):
    """
    Adaptive Repulsion Loss with density-aware spacing.
    
    Unlike fixed-radius repulsion, this adapts spacing based on local intensity:
    - Dark areas (high density): Points can be CLOSE together
    - Light areas (low density): Points must be FAR apart
    
    This is the "physics" of stippling - points pack tighter where more density is needed.
    Without this, Sinkhorn alone would allow 2 points on the same spot.
    """
    
    def __init__(self, base_radius: float = 0.02, min_radius: float = 0.005, max_radius: float = 0.1):
        """
        Initialize adaptive repulsion loss.
        
        Args:
            base_radius: Base repulsion radius (scaled by intensity)
            min_radius: Minimum radius (prevents infinite packing in black)
            max_radius: Maximum radius (prevents explosion in white)
        """
        super().__init__()
        self.base_radius = base_radius
        self.min_radius = min_radius
        self.max_radius = max_radius
    
    def forward(self, points: torch.Tensor, images: torch.Tensor) -> torch.Tensor:
        """
        Compute adaptive repulsion loss.
        
        Args:
            points: (B, N, 2) predicted points in [-1, 1]
            images: (B, 1, H, W) conditioning image
        
        Returns:
            Adaptive repulsion loss (scalar)
        """
        B, N, _ = points.shape
        device = points.device
        
        # 1. Sample image intensity at each point
        grid = points.unsqueeze(2)  # (B, N, 1, 2)
        intensity = F.grid_sample(
            images, grid, mode='bilinear', padding_mode='border', align_corners=True
        ).squeeze(-1).squeeze(1)  # (B, N)
        
        # 2. CRITICAL: Invert intensity for density
        # Dark (intensity~0) = high density = small radius
        # Light (intensity~1) = low density = large radius
        density = 1.0 - intensity
        
        # Formula: R = base_radius / sqrt(density + epsilon)
        # Matches Lloyd's relaxation physics
        dynamic_r = self.base_radius / torch.sqrt(density + 0.1)
        dynamic_r = dynamic_r.clamp(min=self.min_radius, max=self.max_radius)
        
        # 3. Pairwise distance
        loc = points.unsqueeze(2)  # (B, N, 1, 2)
        ref = points.unsqueeze(1)  # (B, 1, N, 2)
        dist = torch.sqrt(torch.sum((loc - ref) ** 2, dim=-1) + 1e-6)  # (B, N, N)
        
        # 4. Mask self-distances
        mask = torch.eye(N, device=device, dtype=torch.bool).unsqueeze(0)
        dist = dist.masked_fill(mask, float('inf'))
        
        # 5. Required distance for each pair
        r_i = dynamic_r.unsqueeze(2)
        r_j = dynamic_r.unsqueeze(1)
        required_dist = (r_i + r_j) / 2.0
        
        # 6. Penalize pairs closer than required
        penalty = F.relu(required_dist - dist)
        
        return torch.mean(penalty)


class DifferentiableRasterizer(nn.Module):
    """Rasterize points into a soft density map via Gaussian splatting."""

    def __init__(self, grid_size: int = 64, sigma: float = 0.02, normalize: bool = True):
        super().__init__()
        self.grid_size = grid_size
        self.sigma = sigma
        self.normalize = normalize

        y = torch.linspace(-1, 1, grid_size)
        x = torch.linspace(-1, 1, grid_size)
        grid_y, grid_x = torch.meshgrid(y, x, indexing="ij")
        coords = torch.stack([grid_x, grid_y], dim=-1).reshape(-1, 2)
        self.register_buffer("grid_coords", coords)

    def forward(self, points: torch.Tensor) -> torch.Tensor:
        B, N, _ = points.shape
        device = points.device
        grid_coords = self.grid_coords.to(device)
        M = grid_coords.shape[0]

        density = torch.zeros(B, M, device=device)
        chunk_size = 1024
        sigma_sq = self.sigma * self.sigma

        for start in range(0, M, chunk_size):
            end = min(start + chunk_size, M)
            grid_chunk = grid_coords[start:end].unsqueeze(0).expand(B, -1, -1)
            dists = torch.cdist(points, grid_chunk, p=2)
            weights = torch.exp(-(dists ** 2) / (2.0 * sigma_sq))
            density[:, start:end] = weights.sum(dim=1)

        if self.normalize:
            max_val = density.max(dim=1, keepdim=True).values.clamp(min=1e-6)
            density = density / max_val

        return density.view(B, 1, self.grid_size, self.grid_size)


class RenderLoss(nn.Module):
    """Render points and compare to target density map."""

    def __init__(self, grid_size: int = 64, sigma: float = 0.02):
        super().__init__()
        self.grid_size = grid_size
        self.rasterizer = DifferentiableRasterizer(grid_size=grid_size, sigma=sigma)

    def forward(self, pred_points: torch.Tensor, input_images: torch.Tensor) -> torch.Tensor:
        pred_density = self.rasterizer(pred_points)
        target_density = F.interpolate(
            input_images,
            size=(self.grid_size, self.grid_size),
            mode="bilinear",
            align_corners=False,
        )
        target_density = 1.0 - target_density
        target_density = target_density.clamp(min=0.0, max=1.0)
        return F.mse_loss(pred_density, target_density)


class UnsupervisedStipplingLoss(nn.Module):
    """
    Combined unsupervised loss for stippling.
    
    No Ground Truth needed! The model learns directly from physics:
    - Sinkhorn: "Match the density" (capacity constraint)
    - AdaptiveRepulsion: "Don't clump" (spacing constraint)
    
    This is the "Neural Solver" for optimal transport with blue noise constraints.
    """
    
    def __init__(
        self,
        sinkhorn_weight: float = 1.0,
        repulsion_weight: float = 0.5,
        render_weight: float = 0.3,
        sinkhorn_blur: float = 0.05,
        sinkhorn_grid_size: int = 32,
        repulsion_base_radius: float = 0.02,
        render_grid_size: int = 64,
        render_sigma: float = 0.02,
    ):
        """
        Initialize unsupervised stippling loss.
        
        Args:
            sinkhorn_weight: Weight for capacity (density matching) loss
            repulsion_weight: Weight for spacing (blue noise) loss
            sinkhorn_blur: Sinkhorn smoothness parameter
            sinkhorn_grid_size: Grid resolution for density target
            repulsion_base_radius: Base radius for repulsion
        """
        super().__init__()
        self.sinkhorn_weight = sinkhorn_weight
        self.repulsion_weight = repulsion_weight
        self.render_weight = render_weight
        
        self.sinkhorn = SinkhornDensityLoss(
            blur=sinkhorn_blur,
            grid_size=sinkhorn_grid_size,
        )
        self.repulsion = AdaptiveRepulsionLoss(
            base_radius=repulsion_base_radius,
        )
        self.render = RenderLoss(grid_size=render_grid_size, sigma=render_sigma)
    
    def forward(
        self,
        pred_points: torch.Tensor,
        input_images: torch.Tensor,
    ) -> Tuple[torch.Tensor, dict]:
        """
        Compute unsupervised stippling loss.
        
        Args:
            pred_points: (B, N, 2) predicted points
            input_images: (B, 1, H, W) conditioning image
        
        Returns:
            total_loss: Scalar loss
            loss_dict: Component losses for logging
        """
        # Capacity loss (density matching via optimal transport)
        sinkhorn_loss = self.sinkhorn(pred_points, input_images)
        
        # Spacing loss (blue noise via adaptive repulsion)
        repulsion_loss = self.repulsion(pred_points, input_images)
        
        # Render loss (tone/shape matching)
        render_loss = self.render(pred_points, input_images)

        # Combined loss
        total_loss = (
            self.sinkhorn_weight * sinkhorn_loss +
            self.repulsion_weight * repulsion_loss +
            self.render_weight * render_loss
        )
        
        loss_dict = {
            "sinkhorn_loss": sinkhorn_loss.item(),
            "repulsion_loss": repulsion_loss.item(),
            "render_loss": render_loss.item(),
            "total_loss": total_loss.item(),
        }
        
        return total_loss, loss_dict


# ============== HYBRID LOSS (Optional) ==============
# If you want to bootstrap with a few GT examples initially

class HybridStipplingLoss(nn.Module):
    """
    Hybrid loss that combines unsupervised physics with optional GT supervision.
    
    Use case: Start with some GT supervision, then "anneal" to pure physics.
    This can help with initial convergence.
    """
    
    def __init__(
        self,
        sinkhorn_weight: float = 1.0,
        repulsion_weight: float = 0.5,
        render_weight: float = 0.3,
        gt_weight: float = 0.0,  # Set > 0 to add GT supervision
        render_grid_size: int = 64,
        render_sigma: float = 0.02,
    ):
        super().__init__()
        self.unsupervised = UnsupervisedStipplingLoss(
            sinkhorn_weight=sinkhorn_weight,
            repulsion_weight=repulsion_weight,
            render_weight=render_weight,
            render_grid_size=render_grid_size,
            render_sigma=render_sigma,
        )
        self.gt_weight = gt_weight
        self.chamfer = ChamferLoss()
    
    def forward(
        self,
        pred_points: torch.Tensor,
        input_images: torch.Tensor,
        gt_points: Optional[torch.Tensor] = None,
    ) -> Tuple[torch.Tensor, dict]:
        """Compute hybrid loss."""
        total_loss, loss_dict = self.unsupervised(pred_points, input_images)
        
        if gt_points is not None and self.gt_weight > 0:
            chamfer_loss = self.chamfer(pred_points, gt_points)
            total_loss = total_loss + self.gt_weight * chamfer_loss
            loss_dict["chamfer_loss"] = chamfer_loss.item()
            loss_dict["total_loss"] = total_loss.item()
        
        return total_loss, loss_dict


class ChamferLoss(nn.Module):
    """Chamfer distance (for optional hybrid training)."""
    
    def forward(self, preds: torch.Tensor, targets: torch.Tensor) -> torch.Tensor:
        x = preds.unsqueeze(2)
        y = targets.unsqueeze(1)
        dist = torch.pow(x - y, 2).sum(-1)
        
        min_dist_pred_to_target, _ = torch.min(dist, dim=2)
        min_dist_target_to_pred, _ = torch.min(dist, dim=1)
        
        return torch.mean(min_dist_pred_to_target) + torch.mean(min_dist_target_to_pred)


